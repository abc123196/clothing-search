-- 任務6：圖片管理表（一件商品可有多張圖，main 為主圖；match_level 記錄照片與品項的吻合度）
CREATE TABLE product_images (
  image_id INT AUTO_INCREMENT PRIMARY KEY,
  product_id VARCHAR(10) NOT NULL,
  image_url VARCHAR(255) NOT NULL,
  image_type VARCHAR(20) NOT NULL DEFAULT 'main',
  match_level VARCHAR(10) NOT NULL,
  source_file VARCHAR(40),
  UNIQUE KEY uq_product_type (product_id, image_type),
  FOREIGN KEY (product_id) REFERENCES clothing(product_id) ON DELETE CASCADE,
  CHECK (match_level IN ('exact','close','sample')));
